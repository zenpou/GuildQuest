// Run while the repository's Vite dev server is already listening on 4185.
// This check owns its browser contexts and does not start or stop that server.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

const baseUrl = process.env.GQ_REVIEW_URL || 'http://127.0.0.1:4185/';
const fixtureCandidates = ['artifacts/fixtures/clear.json', 'artifacts/fixtures/conversation.json'];
const chapterIds = require('../src/data/campaign-story.json').map((chapter) => chapter.id);

async function readBaseFixture() {
  for (const candidate of fixtureCandidates) {
    try {
      return JSON.parse(await fs.readFile(path.resolve(candidate), 'utf8'));
    } catch {
      // The clear fixture is generated by the existing story checks. The
      // conversation fixture is a complete new-game fallback for this UI-only
      // review and is enough once the final quest is unlocked below.
    }
  }
  throw new Error('UI review fixture is missing. Run npm run test:browser once to generate artifacts/fixtures/clear.json.');
}

function makeFixture(base, day) {
  const state = JSON.parse(JSON.stringify(base));
  state.day = day;
  state.gold = Math.max(2000, state.gold ?? 0);
  state.rep = Math.max(25, state.rep ?? 0);
  state.finalCleared = false;
  state.expeditions = [];
  state.history = [];
  state.clears = {};
  state.notices = [];
  state.pendingTags = [];
  state.dispatchedToday = false;
  state.hiredToday = false;
  state.candidates = [];
  if (state.campaign) {
    state.campaign.prologueSeen = true;
    state.campaign.introComplete = true;
    state.campaign.jobChanged = true;
    state.campaign.seenChapters = [...chapterIds];
  }
  for (const [index, adventurer] of state.adventurers.entries()) {
    adventurer.status = 'idle';
    adventurer.injuryDays = 0;
    adventurer.fatigue = index === 0 ? 45 : 10;
  }
  return state;
}

async function openDispatch(context, fixture, errors, label) {
  await context.addInitScript((raw) => localStorage.setItem('guildquest_save_v1', raw), JSON.stringify(fixture));
  const page = await context.newPage();
  if (errors) page.on('pageerror', (error) => errors.push(`${label}: ${error.message}`));
  await page.goto(`${baseUrl}?uiReview=1`, { waitUntil: 'domcontentloaded' });
  await page.locator('.desk-main').waitFor();
  await page.locator('.desk-tabs').getByRole('button', { name: /派遣/ }).click();
  await page.locator('.dispatch-layout').waitFor();
  return page;
}

async function clickFinalQuestWithKeyboard(page) {
  const card = page.locator('[data-focus-key="quest:q_drake"]');
  assert.equal(await card.getAttribute('role'), 'button');
  assert.equal(await card.getAttribute('tabindex'), '0');
  await card.focus();
  await card.press('Enter');
  assert.equal(await card.getAttribute('aria-pressed'), 'true');
  assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('data-focus-key')), 'quest:q_drake');
}

async function checkViewport(browser, fixture, name, width, height, errors) {
  const context = await browser.newContext({ viewport: { width, height }, reducedMotion: 'reduce' });
  const page = await openDispatch(context, fixture, errors, name);
  await clickFinalQuestWithKeyboard(page);

  const preview = page.locator('.dispatch-preview-card');
  const initialText = await preview.innerText();
  assert.match(initialText, /戦力の目安430/);
  assert.match(initialText, /4人推奨/);
  assert.match(initialText, /回復薬/);
  assert.match(initialText, /回復役/);
  assert.match(initialText, /帰還予定: 30日目/);

  const member = page.locator('[data-focus-key="dispatch-member:c_aldo"]');
  assert.equal(await member.getAttribute('role'), 'button');
  assert.equal(await member.getAttribute('tabindex'), '0');
  await member.focus();
  await member.press(' ');
  assert.equal(await member.getAttribute('aria-pressed'), 'true');
  assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('data-focus-key')), 'dispatch-member:c_aldo');
  assert.match(await page.locator('.dispatch-party-status').first().innerText(), /1\/4人選択/);
  assert.match(await preview.innerText(), /疲労40超/);

  const overflow = await page.evaluate(() => ({
    document: document.documentElement.scrollWidth > window.innerWidth + 1,
    body: document.body.scrollWidth > window.innerWidth + 1,
    layout: [...document.querySelectorAll('.dispatch-layout')].some((element) => element.scrollWidth > element.clientWidth + 1),
  }));
  const layoutBoxes = await page.evaluate(() => [...document.querySelectorAll('.dispatch-column')].map((element) => {
    const rect = element.getBoundingClientRect();
    return { className: element.className, x: Math.round(rect.x), y: Math.round(rect.y), width: Math.round(rect.width), height: Math.round(rect.height) };
  }));
  assert.deepEqual(overflow, { document: false, body: false, layout: false }, `${name}: horizontal overflow`);
  await page.evaluate(() => document.body.scrollTo(0, 0));
  await page.screenshot({ path: `artifacts/ui-review-${name}.png` });
  await preview.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `artifacts/ui-review-${name}-readiness.png` });
  const record = {
    viewport: [width, height],
    keyboardQuest: true,
    keyboardMember: true,
    finalWarnings: ['4人推奨', '回復薬', '回復役', '疲労40超'],
    returnDate: '30日目',
    focusRestored: true,
    overflow: false,
    layoutBoxes,
  };
  await context.close();
  return record;
}

(async () => {
  await fs.mkdir('artifacts', { recursive: true });
  const base = await readBaseFixture();
  const fixture = makeFixture(base, 27);
  const overdueFixture = makeFixture(base, 28);
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const errors = [];
  const records = [];
  try {
    for (const [name, width, height] of [['desktop', 1440, 1000], ['tablet', 900, 900], ['mobile', 390, 844], ['small', 320, 568]]) {
      records.push(await checkViewport(browser, fixture, name, width, height, errors));
    }

    const overdueContext = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
    const overduePage = await openDispatch(overdueContext, overdueFixture, errors, 'overdue');
    await overduePage.locator('[data-focus-key="quest:q_drake"]').click();
    const overdueText = await overduePage.locator('.dispatch-preview-card').innerText();
    assert.match(overdueText, /帰還予定: 31日目/);
    assert.match(overdueText, /期限超過/);
    await overduePage.locator('.dispatch-preview-card').scrollIntoViewIfNeeded();
    await overduePage.screenshot({ path: 'artifacts/ui-review-overdue.png' });
    records.push({ viewport: [390, 844], overdueReturnDate: '31日目', overdueWarning: true });
    await overdueContext.close();

    // A party that already departed on time must not be told it missed departure.
    const inFlight = makeFixture(base, 28);
    inFlight.expeditions = [{ ...base.history.find(r => r.questId === 'q_drake'), questId: 'q_drake', startDay: 27, returnDay: 30 }];
    const activeContext = await browser.newContext({ viewport: { width: 900, height: 900 } });
    const activePage = await openDispatch(activeContext, inFlight, errors, 'in-flight');
    await activePage.getByRole('button', { name: 'ホーム', exact: true }).click();
    assert.match(await activePage.locator('.home-goal').innerText(), /派遣中。30日目に帰還予定/);
    assert.doesNotMatch(await activePage.locator('.home-goal').innerText(), /出発期限超過/);
    await activeContext.close();

    const cleared = makeFixture(base, 31);
    cleared.finalCleared = true;
    const clearedContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
    const clearedPage = await openDispatch(clearedContext, cleared, errors, 'cleared');
    await clearedPage.getByRole('button', { name: 'ホーム', exact: true }).click();
    assert.match(await clearedPage.locator('.desk-stats').innerText(), /31日目（延長）/);
    assert.match(await clearedPage.locator('.home-goal').innerText(), /目標達成/);
    assert.doesNotMatch(await clearedPage.locator('.home-goal').innerText(), /挑もう|出発が必要/);
    await clearedContext.close();
    records.push({ inFlightDeadline: true, clearedGoal: true, extendedDayLabel: true });

    assert.deepEqual(errors, []);
    const result = { baseUrl, records, errors };
    await fs.writeFile('artifacts/ui-review.json', JSON.stringify(result, null, 2));
    console.log(JSON.stringify(result, null, 2));
  } finally {
    await browser.close();
  }
})().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
